#!/usr/bin/env node
/**
 * Wires release signing into the generated Android project.
 *
 * `expo prebuild` regenerates apps/mobile/android from scratch, so anything
 * edited there is lost on the next run. This runs after every prebuild and
 * injects the signing config, making `gradlew assembleRelease` produce a
 * properly signed APK instead of one signed with the debug key (which is what
 * prebuild does by default).
 *
 * Credentials come from, in order of precedence:
 *   1. MM_UPLOAD_STORE_FILE / MM_UPLOAD_STORE_PASSWORD / MM_UPLOAD_KEY_ALIAS /
 *      MM_UPLOAD_KEY_PASSWORD environment variables
 *   2. apps/mobile/.secrets/keystore.properties
 *
 * If neither is present the release build keeps Expo's debug signing, which
 * installs fine but is rejected by Google Play. A warning is printed so the
 * difference is never silent.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const buildGradle = path.join(root, 'android', 'app', 'build.gradle');
const manifestFile = path.join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
const propsFile = path.join(root, '.secrets', 'keystore.properties');

function readProperties(file) {
  if (!fs.existsSync(file)) return {};
  return Object.fromEntries(
    fs
      .readFileSync(file, 'utf8')
      .split('\n')
      .map(line => line.trim())
      .filter(line => line && !line.startsWith('#') && line.includes('='))
      .map(line => {
        const idx = line.indexOf('=');
        return [line.slice(0, idx).trim(), line.slice(idx + 1).trim()];
      }),
  );
}

if (!fs.existsSync(buildGradle)) {
  console.error('android/app/build.gradle not found. Run `pnpm prebuild:android` first.');
  process.exit(1);
}

const file = readProperties(propsFile);
const cfg = {
  storeFile: process.env.MM_UPLOAD_STORE_FILE || file.MM_UPLOAD_STORE_FILE,
  storePassword: process.env.MM_UPLOAD_STORE_PASSWORD || file.MM_UPLOAD_STORE_PASSWORD,
  keyAlias: process.env.MM_UPLOAD_KEY_ALIAS || file.MM_UPLOAD_KEY_ALIAS,
  keyPassword: process.env.MM_UPLOAD_KEY_PASSWORD || file.MM_UPLOAD_KEY_PASSWORD,
};

let source = fs.readFileSync(buildGradle, 'utf8');

if (!cfg.storeFile || !cfg.storePassword || !cfg.keyAlias || !cfg.keyPassword) {
  console.warn(
    '[android-signing] No release keystore configured, so `assembleRelease` will be ' +
      'signed with the debug key. It installs, but Google Play rejects it.\n' +
      `  Create one with apps/mobile/scripts/generate-upload-keystore.sh, then\n` +
      `  set MM_UPLOAD_* variables or fill in ${path.relative(process.cwd(), propsFile)}.`,
  );
  process.exit(0);
}

if (!fs.existsSync(path.resolve(root, cfg.storeFile))) {
  console.error(`[android-signing] Keystore not found: ${cfg.storeFile}`);
  process.exit(1);
}

// `storeFile file(...)` inside app/build.gradle resolves against android/app/,
// while the properties file holds a path relative to apps/mobile/. Convert it,
// using forward slashes so the result works on every platform.
const keystoreForGradle = path
  .relative(path.join(root, 'android', 'app'), path.resolve(root, cfg.storeFile))
  .split(path.sep)
  .join('/');
if (!keystoreForGradle.startsWith('..')) {
  console.error(
    `[android-signing] Keystore must live outside android/app so prebuild cannot ` +
      `delete it: ${keystoreForGradle}`,
  );
  process.exit(1);
}

// Idempotent: drop any block this script added on a previous run before
// re-inserting, so repeated prebuild + configure cycles stay stable.
source = source.replace(
  /\n {4}\/\/ BEGIN android-signing[\s\S]*?\/\/ END android-signing\n/g,
  '\n',
);

const releaseConfig = `
    // BEGIN android-signing (generated by scripts/configure-android-release.js)
    release {
        storeFile file('${keystoreForGradle}')
        storePassword '${cfg.storePassword.replace(/'/g, "\\'")}'
        keyAlias '${cfg.keyAlias.replace(/'/g, "\\'")}'
        keyPassword '${cfg.keyPassword.replace(/'/g, "\\'")}'
    }
    // END android-signing
`;

// Insert the release signingConfig alongside the debug one.
const debugConfigEnd = "            keyPassword 'android'\n        }\n";
if (!source.includes(debugConfigEnd)) {
  console.error('[android-signing] Could not find the debug signingConfig anchor.');
  process.exit(1);
}
source = source.replace(
  debugConfigEnd,
  `${debugConfigEnd}${releaseConfig}`,
);

// Point the release build type at the new config. Gradle takes the last
// `signingConfig` in a block, so the prebuild `signingConfigs.debug` line has to
// be replaced rather than shadowed, or the APK silently ships debug-signed.
const releaseStart = source.indexOf('\n        release {');
if (releaseStart === -1) {
  console.error('[android-signing] Could not find the release buildType.');
  process.exit(1);
}
const releaseBodyStart = source.indexOf('\n', releaseStart + 1) + 1;
const nextBlock = source.indexOf('\n        }', releaseBodyStart);
if (nextBlock === -1) {
  console.error('[android-signing] Could not find the end of the release buildType.');
  process.exit(1);
}
const releaseBody = source.slice(releaseBodyStart, nextBlock);

// Exactly one signingConfig line must survive, pointing at the release config.
// Gradle takes the *last* one in a block, so leaving prebuild's
// `signingConfigs.debug` behind would ship a debug-signed APK with no warning.
// Replacing before de-duplicating (rather than filtering then replacing) keeps
// re-runs idempotent: the line this script wrote is itself the one rewritten.
let seenSigning = false;
const keptLines = releaseBody.split('\n').filter(line => {
  if (!/signingConfig\s+signingConfigs\.\w+/.test(line)) return true;
  if (seenSigning) return false;
  seenSigning = true;
  return true;
});
if (!seenSigning) {
  console.error('[android-signing] The release buildType has no signingConfig line.');
  process.exit(1);
}
const rebuiltBody = keptLines
  .map(line =>
    /signingConfig\s+signingConfigs\.\w+/.test(line)
      ? line.replace(/signingConfig\s+signingConfigs\.\w+/, 'signingConfig signingConfigs.release')
      : line,
  )
  .join('\n');
source = source.slice(0, releaseBodyStart) + rebuiltBody + source.slice(nextBlock);

fs.writeFileSync(buildGradle, source);
console.log(`[android-signing] release build will use alias "${cfg.keyAlias}".`);

// Ensure release APK allows HTTP/WS connections to local LAN API servers
if (fs.existsSync(manifestFile)) {
  let manifest = fs.readFileSync(manifestFile, 'utf8');
  if (!manifest.includes('android:usesCleartextTraffic')) {
    manifest = manifest.replace('<application', '<application android:usesCleartextTraffic="true"');
    fs.writeFileSync(manifestFile, manifest);
    console.log('[android-signing] enabled android:usesCleartextTraffic="true" in AndroidManifest.xml.');
  }
}
