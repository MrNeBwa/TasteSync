#!/usr/bin/env bash
# Creates the release upload keystore and its properties file.
#
# The keystore is the app's identity to Google Play. If it is lost, the app can
# never be updated again under the same listing, so back it up somewhere safe
# and keep the password out of version control.
set -euo pipefail

cd "$(dirname "$0")/.."

SECRETS=".secrets"
KEYSTORE="$SECRETS/upload.keystore"
PROPS="$SECRETS/keystore.properties"
ALIAS="${MM_UPLOAD_KEY_ALIAS:-upload}"

if [ -f "$KEYSTORE" ]; then
  echo "$KEYSTORE already exists. Delete it first to generate a new identity."
  exit 1
fi

mkdir -p "$SECRETS"
umask 077

if [ -n "${MM_UPLOAD_STORE_PASSWORD:-}" ]; then
  PASS="$MM_UPLOAD_STORE_PASSWORD"
  echo "Using MM_UPLOAD_STORE_PASSWORD from the environment."
else
  PASS=$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 24)
fi

keytool -genkeypair -v \
  -keystore "$KEYSTORE" \
  -alias "$ALIAS" \
  -keyalg RSA -keysize 2048 -validity 10950 \
  -storepass "$PASS" -keypass "$PASS" \
  -dname "CN=Movie Match, OU=Mobile, O=Movie Match, C=RU"

cat > "$PROPS" <<EOF
# Generated by scripts/generate-upload-keystore.sh. Never commit this file.
MM_UPLOAD_STORE_FILE=$KEYSTORE
MM_UPLOAD_STORE_PASSWORD=$PASS
MM_UPLOAD_KEY_ALIAS=$ALIAS
MM_UPLOAD_KEY_PASSWORD=$PASS
EOF

rm -f "$SECRETS/keystore-password.txt"
echo
echo "Wrote $KEYSTORE and $PROPS (both gitignored)."
echo "Back the keystore up now: losing it means the Play listing can never be updated."
